print("=== PROGRAM HITUNG KELILING LINGKARAN ===")

# 1. Menerima Input dari Pengguna
jari_jari = float(input("Masukkan jari-jari lingkaran (cm): "))

# 2. Proses Perhitungan (Sesuai Identifikasi IPO)
keliling = 2 * 3.14 * jari_jari


# 3. Menampilkan Output
print("\n--- HASIL PERHITUNGAN ---")
print(f"Keliling lingkaran: {keliling} cm")
